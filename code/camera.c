/*********************************************************************************************************************
* 文件名称          camera.c
* 功能简介          总钻风 MT9V03X 摄像头采集（188x120 灰度）
*
* ******************************* 采图流程 *******************************
*   VSY 下降沿  -> 场中断 -> 打开 DMA
*   PCLK 每个沿 -> ERU 触发 DMA，把 P00 口的 8 位数据搬进 mt9v03x_image
*   一帧搬完     -> DMA 完成中断 -> 库里置 mt9v03x_finish_flag 并【关掉 DMA】
*                -> 我们紧接着在同一个中断里 camera_dma_copy() 把整帧拷到 camera_image
*
* ******************************* 为什么拷贝要放在中断里 *******************************
*   一帧采完到下一场 VSY 之间只有 20ms（50fps），过了这个窗口 DMA 就会重新往
*   mt9v03x_image 里覆盖。如果主循环里拷贝，碰上刷屏（一次十几毫秒）就很容易
*   在 DMA 正在写的时候去读，拷到"上半帧是新的、下半帧是旧的"的撕裂图像 ——
*   屏幕上就是横着的白色条纹。
*   放进 DMA 完成中断里拷贝，DMA 此刻一定是关着的，物理上不可能撕裂。
*
*   拷贝要 22KB，占用中断约 0.1~0.2ms（300MHz），对 20ms 周期完全无压力。
*   万一主循环还在用上一帧（camera_busy），这一帧就丢掉不拷 —— 丢帧只是画面
*   慢一点，撕裂会让图像算法读到假数据，更糟。
*********************************************************************************************************************/

#include "camera.h"

//==================================================== 可调参数 ====================================================
#define CAMERA_RETRY_MAX        (3)                     // 初始化失败重试次数

//==================================================== 全局变量 ====================================================
uint8  camera_image[CAMERA_H][CAMERA_W];                // 主循环在用的那一份（稳定的完整帧）

//==================================================== 内部变量 ====================================================
static uint8  camera_ok_flag    = 0;                    // 1 = 初始化成功
static uint32 camera_frame_cnt  = 0;                    // 已经拷好的帧数
static uint32 camera_last_ms    = 0;                    // 上一帧的时刻

static volatile uint8 camera_ready = 0;                 // 有新帧等着主循环处理
static volatile uint8 camera_busy  = 0;                 // 主循环正在用 camera_image

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      摄像头初始化
// 备注信息      mt9v03x_init() 内部有 system_delay_ms(200) 和串口协商，会阻塞几百毫秒，
//               所以放在屏幕/编码器/电机/舵机都初始化完之后再调用。
//               返回 0 表示成功，1 表示失败（逐飞库的约定）。
//-------------------------------------------------------------------------------------------------------------------
void camera_setup (void)
{
    uint8 i;

    camera_ok_flag    = 0;
    camera_frame_cnt  = 0;
    camera_ready      = 0;
    camera_busy       = 0;
    camera_last_ms    = system_getval_ms();

    for(i = 0; i < CAMERA_RETRY_MAX; i++)
    {
        if(0 == mt9v03x_init())                         // 0 = 成功
        {
            camera_ok_flag = 1;
            break;
        }
    }

    if(camera_ok_flag)
    {
        mt9v03x_finish_flag = 0;                        // 丢掉初始化期间攒下的标志
        camera_last_ms = system_getval_ms();
    }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      【中断里调用】把刚采完的一帧拷到 camera_image
// 备注信息      在 user/isr.c 的 DMA 完成中断里、camera_dma_handler() 之后调用。
//               靠 camera_busy 做单缓冲保护：主循环正在用就整帧丢掉，绝不覆盖。
//-------------------------------------------------------------------------------------------------------------------
void camera_dma_copy (void)
{
    if(0 == camera_ok_flag)
    {
        return;
    }

    if(0 == mt9v03x_finish_flag)                        // 库没置标志就说明不是正常采完
    {
        return;
    }

    mt9v03x_finish_flag = 0;                            // 先清标志

    if(camera_busy)                                     // 主循环还在用，这一帧丢掉
    {
        return;
    }

    memcpy(camera_image, mt9v03x_image, sizeof(camera_image));

    camera_frame_cnt++;
    camera_last_ms = system_getval_ms();
    camera_ready   = 1;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      取一帧新图像
// 返回参数      1 = 拿到新帧（camera_image 里是完整的一帧）；0 = 还没有新帧
// 备注信息      返回 1 之后到调用 camera_release() 之前，中断不会再来覆盖 camera_image
//-------------------------------------------------------------------------------------------------------------------
uint8 camera_update (void)
{
    if(0 == camera_ok_flag)
    {
        return 0;
    }

    if(0 == camera_ready)
    {
        return 0;
    }

    camera_ready = 0;
    camera_busy  = 1;                                   // 锁住，中断这一段时间不许拷

    return 1;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      放行：告诉摄像头模块主循环这一圈用完了
//-------------------------------------------------------------------------------------------------------------------
void camera_release (void)
{
    camera_busy = 0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      摄像头初始化是否成功
//-------------------------------------------------------------------------------------------------------------------
uint8 camera_is_ok (void)
{
    return camera_ok_flag;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      已经处理过的帧数
//-------------------------------------------------------------------------------------------------------------------
uint32 camera_get_frame (void)
{
    return camera_frame_cnt;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      距上一帧过去了多少毫秒
//-------------------------------------------------------------------------------------------------------------------
uint32 camera_get_idle_ms (void)
{
    return system_getval_ms() - camera_last_ms;
}