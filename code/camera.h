/*********************************************************************************************************************
* 文件名称          camera.h
* 功能简介          总钻风 MT9V03X 摄像头采集（188 x 120 灰度）
*
* *************************** 接线 ***************************
*   摄像头管脚        单片机管脚        说明
*   PCLK             P02_1            像素时钟，走 ERU 通道2 触发 DMA
*   VSY              P02_0            场中断，走 ERU 通道3
*   D0 ~ D7          P00_0 ~ P00_7    8 位并行数据，必须从 P00_0 开始连续 8 个
*   TXD / RXD        P02_3 / P02_2    配置串口（同时也是 SCCB 的 SCL / SDA）
*   VCC / GND        3.3V / GND
*
*   这几个引脚和逐飞库 zf_device_mt9v03x.h 里的默认宏定义完全一致，
*   所以不需要改库文件，也不需要改 user/isr.c 里的中断钩子。
*
* *************************** 采图是怎么跑的 ***************************
*   1. VSY 下降沿 -> 场中断 -> 打开 DMA，把目的地址指到 mt9v03x_image
*   2. PCLK 每个上升沿 -> ERU 触发一次 DMA，把 P00 口上那 8 位数据搬进内存
*   3. 一整帧搬完（188*120 = 22560 字节）-> DMA 完成中断 -> 置 mt9v03x_finish_flag，关 DMA
*   一帧只要 3.8ms 左右，剩下 16ms 图像是静止的，可以慢慢处理。
*
* *************************** 为什么还要一份 camera_image ***************************
*   下一场的 VSY 一到，DMA 会立刻开始往 mt9v03x_image 里覆盖。
*   所以拿到 finish_flag 之后第一件事就是整帧 memcpy 到 camera_image，
*   后面的二值化、边线提取、屏幕显示全部只看 camera_image，
*   不管主循环跑得多慢，都不可能看到"半新半旧"的撕裂图像。
*********************************************************************************************************************/

#ifndef _camera_h_
#define _camera_h_

#include "zf_common_headfile.h"

//==================================================== 图像尺寸 ====================================================
#define CAMERA_W        (MT9V03X_W)                     // 188
#define CAMERA_H        (MT9V03X_H)                     // 120

//==================================================== 全局变量 ====================================================
extern uint8 camera_image[CAMERA_H][CAMERA_W];          // 稳定的图像副本，图像算法只读这一份

//==================================================== 对外接口 ====================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介      摄像头初始化（内部会阻塞几百毫秒做串口协商，请放在其它外设之后）
// 备注信息      失败会自动重试 CAMERA_RETRY_MAX 次，用 camera_is_ok() 查结果
//-------------------------------------------------------------------------------------------------------------------
void    camera_setup       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      【中断里调用】把刚采完的一帧拷到 camera_image
// 备注信息      由 user/isr.c 的 DMA 完成中断在 camera_dma_handler() 之后调用。
//               这时库已经把 DMA 关掉了，mt9v03x_image 是完整静止的一帧，
//               在这里拷贝绝不可能拷到"正在被 DMA 覆盖"的半帧，也就不会出现撕裂白条纹。
//               如果主循环还在用上一帧（camera_busy），这一帧直接丢掉 —— 丢帧好过撕裂。
//-------------------------------------------------------------------------------------------------------------------
void    camera_dma_copy   (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      告诉摄像头模块"主循环这一圈用完了"，放行下一帧的拷贝
// 备注信息      在 user/cpu0_main.c 的主循环最后调用一次
//-------------------------------------------------------------------------------------------------------------------
void    camera_release    (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      取一帧新图像
// 返回参数      1 = 拿到了新的一帧（已经拷进 camera_image）；0 = 还没有新帧
// 备注信息      主循环里无条件反复调用即可，它自己会判断有没有新帧
//-------------------------------------------------------------------------------------------------------------------
uint8   camera_update     (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      摄像头初始化是否成功
//-------------------------------------------------------------------------------------------------------------------
uint8   camera_is_ok      (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      已经处理过的帧数（正常约 50 帧/秒，屏幕上看它有没有在涨就知道摄像头活没活）
//-------------------------------------------------------------------------------------------------------------------
uint32  camera_get_frame  (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      距上一帧过去了多少毫秒（超过 200ms 基本就是掉线了）
//-------------------------------------------------------------------------------------------------------------------
uint32  camera_get_idle_ms(void);

#endif
