/*********************************************************************************************************************
* 文件名称          display.h
* 功能简介          IPS200 Pro（2.0 寸 SPI 智能屏）显示接口
*
* *************************** IPS200 Pro 和 IPS200 的区别 ***************************
*   IPS200     是"哑屏"：主控直接通过 SPI 发像素数据画点、画字。
*   IPS200 Pro 是"智能屏"：屏幕自带 GUI 引擎，主控只通过 SPI 发【控件命令】
*              （创建 label/image/table 等组件、更新内容），屏幕自己负责渲染。
*              所以驱动方式完全不同，但接线和 IPS200 一模一样，不用改线。
*********************************************************************************************************************/

#ifndef _display_h_
#define _display_h_

#include "zf_common_headfile.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      屏幕初始化（IPS200 Pro，SPI 方式，竖屏 240x320）
//-------------------------------------------------------------------------------------------------------------------
void display_init         (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      显示控制周期（单位 ms）
//-------------------------------------------------------------------------------------------------------------------
void display_show_period  (uint32 period_ms);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      循迹模式显示：顶部是摄像头图像 + 左右边线 + 中线，下方是 3 列 x 6 行状态数字
//
//   图像区 = 摄像头原图（188x120，水平居中），按本帧实际阈值二值化后的样子
//   蓝线 = 左边线     绿线 = 右边线     红线 = 中线
//
//   下方 3 列：
//     第一列：ERR 图像偏差 / SDR 舵机打角 / RAT 弯道减速比例 / DTY 舵机占空比 / THR 阈值 / VLD 有效行数
//     第二列：TOP 最远有效行 / STA 状态 / FRM 帧数 / GMN 灰度最小 / GMX 灰度最大 / PRD 控制周期
//     第三列：T1/A1/D1 电机1 目标/实际/占空比   T2/A2/D2 电机2 目标/实际/占空比
//-------------------------------------------------------------------------------------------------------------------
void display_update_track (void);

#endif
