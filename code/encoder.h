/*********************************************************************************************************************
* 文件名称          encoder.h
* 功能简介          两路编码器读取接口
*********************************************************************************************************************/

#ifndef _encoder_h_
#define _encoder_h_

#include "zf_common_headfile.h"

//==================================================== 枚举定义 ====================================================
// 注意：这里故意不叫 encoder_index_enum
//       因为开源库的 zf_driver_encoder.h 里已经有一个同名的枚举（TIM2_ENCODER ... TIM6_ENCODER），
//       重名会直接编译报错。
typedef enum
{
    ENCODER_ID_1 = 0,           // 编码器1：计数 P10_3  方向 P10_1
    ENCODER_ID_2,               // 编码器2：计数 P20_3  方向 P20_0

    ENCODER_ID_COUNT,
}encoder_id_enum;

//==================================================== 对外接口 ====================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介      编码器初始化（两路）
//-------------------------------------------------------------------------------------------------------------------
void  encoder_init        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      编码器刷新：读增量 -> 累加总计数 -> 滤波出速度
// 备注信息      需要固定周期调用，屏幕上"增量/速度"才有一致的物理含义
//               本工程在 main 循环里每 ENCODER_UPDATE_MS 毫秒调一次
//-------------------------------------------------------------------------------------------------------------------
void  encoder_update      (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取本周期增量（脉冲/周期），正负表示转向
//-------------------------------------------------------------------------------------------------------------------
int16 encoder_get_delta   (encoder_id_enum encoder_n);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取累计脉冲数
//-------------------------------------------------------------------------------------------------------------------
int32 encoder_get_total   (encoder_id_enum encoder_n);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取滤波后的速度（脉冲/周期）
//-------------------------------------------------------------------------------------------------------------------
int16 encoder_get_speed   (encoder_id_enum encoder_n);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      累计脉冲清零
//-------------------------------------------------------------------------------------------------------------------
void  encoder_clear_total (encoder_id_enum encoder_n);

#endif
