/*********************************************************************************************************************
* 文件名称          imu.h
* 功能简介          IMU660RB 陀螺仪：取偏航角速度，积分成航向角
*
* *************************** 为什么需要它 ***************************
*   环岛状态机要判"车已经转过大约 270°了" —— 这正是国一参考工程用陀螺仪积分
*   （它那边是 icm_x）做的事，比拿编码器距离去猜可靠得多。
*
* *************************** 接线 ***************************
*   IMU660RB 走硬件 SPI0：
*       SCLK P20_11     MOSI P20_14     MISO P20_12     CS P20_13
*   这四个引脚和《推荐IO分配.txt》里"ICM20602"那一栏完全一致 ——
*   那个模块位本来就是留给 IMU 的，只是模块上贴的芯片是 IMU660RB。
*   和摄像头（P00/P02）、屏幕（P15，走 SPI2）、舵机（P33_9）、电机（P21）都不冲突。
*
* *************************** 怎么用 ***************************
*   1. 上电初始化（【车必须静止】，里面要校零）：imu_init();
*   2. 周期采样：imu_update();   已经放进 user/isr.c 的 cc60_pit_ch0_isr，
*      跟着 20ms 编码器/速度环中断一起跑 —— 采样周期均匀，积分才准。
*   3. 读航向角：imu_get_yaw_deg();    右转为负、左转为正（和图像偏差的正负约定一致）
*
* *************************** 已实测确认（2026-10）***************************
*   偏航轴 = Z（板子水平放置，默认值就是对的）；原始角速度方向是反的，所以 IMU_YAW_DIR = (1.0f)，
*   右转时 YAW 往负走。
*
* *************************** 航向标定：先分清"漂移"还是"比例" ***************************
*   体检方法：车平放静止 30 秒，看 YAW。
*     A. YAW 一直在慢慢走（比如 30 秒走了 10 度以上）——【零偏残留】，是漂移。
*        处理：先确认校零时车真的没动；不够就把 IMU_GYRO_DEADBAND 从 1.5 加到 2.5（度/秒）。
*     B. 静止不动，但【转一圈回来对不上】（比如转 360 度回来差 20 度）——【比例误差】。
*        处理：用 IMU_YAW_SCALE 修（下面有标定方法）。
*   两者会同时存在，先把 A 治干净，再标 B。
*********************************************************************************************************************/

#ifndef _imu_h_
#define _imu_h_

#include "zf_common_headfile.h"

//==================================================== 偏航轴 ====================================================
#define IMU_YAW_AXIS_X      (0)
#define IMU_YAW_AXIS_Y      (1)
#define IMU_YAW_AXIS_Z      (2)

// 【实测确认 2026-10】偏航轴 = Z（默认值就是对的，不用改）；方向需要反，所以 IMU_YAW_DIR = (1.0f)。
//   验证过程：车平放、绕竖直轴转车身 -> GZ 变化最明显；右转时 YAW 往负走。
#define IMU_YAW_AXIS        (IMU_YAW_AXIS_Z)    // 实测：偏航轴是 Z
#define IMU_YAW_DIR         (1.0f)              // 实测：右转 YAW 变负（原始角速度是反的，所以是 +1）

//==================================================== 零偏校零 ====================================================
// 上电静止采样求零偏。先等一会儿再采 —— 舵机刚初始化完会抖，抖着校出来的零偏是错的。
#define IMU_ZERO_SETTLE_MS  (300)               // 开始采样前先静置这么久（毫秒）
#define IMU_ZERO_SAMPLES    (300)               // 采样次数（300 x 2ms = 约 0.6 秒）
#define IMU_ZERO_DELAY_MS   (2)                 // 每次采样间隔（毫秒）
#define IMU_ZERO_TRIM       (40)                // 原始 LSB，约 2.8 度/秒。第二遍只保留离粗平均这么近的采样，
                                                // 校零期间万一被碰一下 / 桌上震一下，那几拍会被剔掉

//==================================================== 积分参数 ====================================================
#define IMU_GYRO_DEADBAND   (1.5f)              // 静止死区（度/秒）：零偏残留不参与积分，否则航向一直漂

// 【已实测确认 2026-10：比例不用修，IMU_YAW_SCALE = 1.0f 就是对的】
//   标定方法（留着以后换模块再用）：把车【平放在地面】上、车头对齐一条参考线，
//   贴着地面同方向连续转 N 整圈（比如 5 圈 = 1800 度，每圈 3~5 秒），转完重新对齐参考线，
//   读屏幕上 YAW 的变化量 |YAW|，则
//       IMU_YAW_SCALE = 真实转过的角度 / |YAW|
//   本车实测：转 5 圈后 |YAW| 在 1800 附近（只差几度），增益本来就是准的。
//   【别拿在手里转】手转会不自觉地把车身转歪，倾斜会把偏航漏到 X/Y 轴，
//   Z 轴积分必然偏小 —— 本车手持测法曾读出 20 度的假误差，贴地测法就没有。
#define IMU_YAW_SCALE       (1.0f)              // 实测确认：不用修（贴地转 5 圈 |YAW| 约 1800）

//==================================================== 结果 ====================================================
extern float32 imu_gyro_dps[3];                 // 三轴角速度（度/秒，已扣零偏），屏幕上看它找偏航轴
extern float32 imu_yaw_deg;                     // 积分出来的航向角（度），右转为负

//==================================================== 对外接口 ====================================================
void    imu_init        (void);                 // 初始化 + 上电静止校零（调用时车必须静止）
void    imu_update      (void);                 // 周期调用：读陀螺仪 -> 扣零偏 -> 死区 -> 积分
void    imu_reset_yaw   (float32 deg);          // 把航向角置成指定值（比如进环岛前清零）
uint8   imu_is_ok       (void);                 // 1 = 初始化成功
float32 imu_get_yaw_deg (void);                 // 航向角（度）
float32 imu_get_yaw_rate(void);                 // 偏航角速度（度/秒，已按 IMU_YAW_DIR / IMU_YAW_SCALE 修正）

#endif