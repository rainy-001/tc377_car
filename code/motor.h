/*********************************************************************************************************************
* 文件名称          motor.h
* 功能简介          两路电机速度闭环控制接口（PWM + DIR 驱动，编码器测速，PID 调速）
*********************************************************************************************************************/

#ifndef _motor_h_
#define _motor_h_

#include "zf_common_headfile.h"

//==================================================== 可调参数 ====================================================
// 上电后先停 MOTOR_START_DELAY_MS 毫秒再启动速度环
// 这段时间可以在屏幕上确认 ENC 列有没有在动（验证编码器），确认正常后才上闭环
#define MOTOR_START_DELAY_MS        (2000)

//==================================================== 对外接口 ====================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介      闭环初始化（PWM + DIR + PID 参数，PWM 先输出 0）
// 备注信息      编码器请另外调用 encoder_init()
//-------------------------------------------------------------------------------------------------------------------
void    motor_init                  (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      速度闭环控制节拍，每 MOTOR_CONTROL_PERIOD_MS 毫秒调用一次
// 备注信息      流程：读速度 -> PID -> 输出限幅 -> 加减速斜坡 -> 死区补偿 -> 写 PWM -> 堵转检测
//-------------------------------------------------------------------------------------------------------------------
void    motor_control_update        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      设置目标速度（单位：脉冲/控制周期），正数正转、负数反转、0 停
// 参数说明      motor_no        1 或 2
// 参数说明      speed           目标速度
// 使用示例      motor_set_speed(1, 40.0f);       // 电机1 目标 40 脉冲/20ms
//-------------------------------------------------------------------------------------------------------------------
void    motor_set_speed             (uint8 motor_no, float32 speed);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取目标速度
//-------------------------------------------------------------------------------------------------------------------
float32 motor_get_target            (uint8 motor_no);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取实际速度（脉冲/控制周期）
//-------------------------------------------------------------------------------------------------------------------
float32 motor_get_speed             (uint8 motor_no);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取实际占空比（0~10000，带符号）
//-------------------------------------------------------------------------------------------------------------------
float32 motor_get_duty              (uint8 motor_no);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取堵转标志：1 = 堵转
//-------------------------------------------------------------------------------------------------------------------
uint8   motor_get_stall             (uint8 motor_no);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      在线修改某路电机的 PID 参数（会同时清零积分）
// 参数说明      motor_no        1 或 2
//-------------------------------------------------------------------------------------------------------------------
void    motor_set_pid               (uint8 motor_no, float32 kp, float32 ki, float32 kd);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取某路电机的 PID 参数
//-------------------------------------------------------------------------------------------------------------------
void    motor_get_pid               (uint8 motor_no, float32 *kp, float32 *ki, float32 *kd);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      所有电机立即停止（PWM 置 0，目标清零，积分清零）
//-------------------------------------------------------------------------------------------------------------------
void    motor_stop_all              (void);


//-------------------------------------------------------------------------------------------------------------------
// 函数简介      闭环测试：把两路电机目标速度设成 motor.c 顶部的默认值
// 备注信息      由 user/cpu0_main.c 调用
//-------------------------------------------------------------------------------------------------------------------
void    motor_close_loop_test_start (void);

#endif
