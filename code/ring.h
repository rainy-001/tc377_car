/*********************************************************************************************************************
* 文件名称          ring.h
* 功能简介          环岛（圆环）状态机 —— 照 E07_encoder_demo 的环岛代码移植
*
* ******************************* 参考来源：E07_encoder_demo\code\image.c *******************************
*   它那套环岛是【7 个状态 + 纯图像驱动】，函数是 cir_l()（左环，image.c:834）和 cir_R()（右环，image.c:1009），
*   配合三个辅助函数：
*     Get_piont()/Get_piont_R()   在二值图里找环岛的【拐点】（image.c:915 / 1081）
*     buxian_l()/buxian_r() 等    从底行边线往拐点拉一条直线，用这条线当中线的一侧（image.c:957 / 981）
*   状态流转（左环；右环左右镜像）：
*
*     1 起   image.c:839  !lost_right[30] && !lost_right[40] && lost_left[40] && lost_left[42]
*                         && long_road>=38 && cir_l_k<0.4 && cir_l_k>=0 && wide_LR>45
*                         【右边线完整 + 左边线在第 40/42 行丢了 + 视野很长 + 路面很宽 + 曲率适中】
*     1->2   image.c:844  !lost_left[40] && !lost_left[42]      左边界又回来（车已进环）
*     2->3   image.c:864  lost_left[40] && lost_left[42]        走到环岛上半部分
*     3->4   image.c:869  up_piont_x > 20                       找到上拐点
*     4->5   image.c:879  up_piont_x > 40 || !up_piont_flag     拐点靠下 = 已经进环
*     5->6   image.c:884  right_point[37] < right_point[35]     出环特征，同时记 cir_ang = angle
*     6->7   image.c:895  (angle - cir_ang) > 50                【陀螺仪】再转 50 度
*     7->0   image.c:900  !lost_left[control_y] && !lost_right[control_y]   左右都回来 = 出环完成
*                         并置 timer_L = 1000（冷却计数，防止同一个环被重复识别）
*
*   ★ 两个很关键的细节（很多工程都没做）：
*     ① 【环里换一套舵机参数】duoji_pid()（image.c:675）：只要进了环，P 从 0.32 换成 0.38（+19%），I 清零。
*        本工程照做 -> RING_STEER_KP / RING_STEER_KP2。
*     ② 【右环多一条计时兜底】cir_R()（image.c:1067）：7->0 除了"左右不丢"，还"或 youchuhuandejishu>300"。
*        它自己的注释很实在：出环口紧接着一个急弯，"左右不丢"这个条件不一定出现，所以干脆计时兜底。
*        本工程两条都留着（RING_EXIT_TIMEOUT_FRAMES）。
*
* ******************************* 移植到本工程的换算 *******************************
*   E07 是 80x60，本工程是 188x120，所以：
*     行号  本工程 y = E07 的 y x 2 + 1（正好落在本工程扫描的奇数行网格上）。见 RING_ROW()。
*     列/像素  宽度方向 188/80 = 2.35 倍：路宽门槛 45 -> 135，拐点邻域 4 像素 -> 9 像素，4 行 -> 8 行。
*     起环判据 已换成 image.c 的 image_ring_side（原因见下面一段，和分辨率换算无关）。
*     角度  陀螺仪角度不用换算：E07 的 50 度 / 40 度直接搬。
*     时间  E07 的定时计数按它自己的控制频率，本工程换算成帧数（约 50 帧/秒）。
*   【换算依据全部写在 ring.h 注释里，换镜头/换分辨率后这几个数要重新标定。】
*
* ******************************* 本工程额外做的事 *******************************
*   ① 【逐行丢边标志】E07 的检测全靠 lost_left[y] / lost_right[y]（某一行某一侧边线跑到画面外了）。
*      本工程原来没有这个量（单边丢失会被 IMAGE_ALLOW_SINGLE_EDGE 直接补掉），
*      所以在 image.c 里加了 image_lost_l[] / image_lost_r[]，在补线【之前】记下来。
*   ② 【不另外维护补线数组】E07 有 left_bu_point[]/right_bu_point[]/mid_bu_point[] 三套数组，
*      本工程直接改写 image_center_line[]，改完调 image_calc_error() 重算偏差 ——
*      于是 track.c / display.c 里"看偏差"的部分一行都不用改，屏幕上红线也直接变成环岛目标线。
*   ③ 【环里的舵机参数和限速】E07 在 duoji_pid() 里换参数、用 yvan_speed 限速。
*      本工程由 track.c 调 ring_is_active() 来切换（见 track.c 里那段）。
 *
 * ******************************* 起环判据【没有】照抄 E07 —— 踩坑以后改的 *******************************
 *   E07 用 lost_left[40] / lost_left[42]（本工程第 81 / 85 行）判"环这一侧边线跑出画面"。
 *   2026-10 实车实测（把丢边标志打上屏，读数见下面的表格）：
 *       直道 LST 0000      左环入口 LST 1100      右环入口 LST 0000
 *   左环入口确实丢线，但【右环入口同样不丢】—— 我们相机视场比 E07 窄，右环张开那一侧的边线
 *   在画面里还看得见，根本走不到画面外。于是右环永远起不来；左环能起来只是因为它的条件里
 *   那两条"另一侧不丢线"本来就恒真，它其实是【碰巧】成立的。
 *   现在起环改用 image.c 每帧算好的 image_ring_side：按"这一行某一侧边线比【下面一行】同一侧
 *   往外跑了 IMAGE_ELEMENT_OUT_MIN 像素"或"某一侧边线外侧还有成片白点"逐行判，一帧里有
 *   IMAGE_RING_ROW_MIN 行【只有一侧】伸出去，就是那一侧的环岛。
 *   它自己跟自己比，不依赖任何固定行号 / 赛道宽度模型，换镜头也不用重标。
 *   曲率（E07 的 cir_l_k / cir_R_k）一并去掉：实测它在直道读 77、环岛读 9，
 *   和 E07 的尺度预期正好相反，说明它在我们这张图上主要反映透视而不是弯曲，拿它当门槛是错的。
 *
*********************************************************************************************************************/

#ifndef _ring_h_
#define _ring_h_

#include "zf_common_headfile.h"
#include "image.h"

//==================================================== 总开关 ====================================================
#define RING_ENABLE             (0)                     // 1 = 认出环岛就真的绕进去
                                                        // 0 = 关闭环岛（当前）：不绕环，入口按直道通过
                                                        //     同时 image.c 里的 ring_update() 也已注释掉

//==================================================== 行号映射（E07 行号 -> 本工程行号）=========================
#define RING_ROW(e07_y)         ((e07_y) * 2 + 1)

#define RING_R_WIDE             RING_ROW(41)            //  83  量路面宽度（E07 用 41）
#define RING_R_LO               RING_ROW(40)            //  81  状态 1->2 / 2->3 的丢边判据（E07 用 40）
#define RING_R_HI               RING_ROW(42)            //  85  丢边判据（E07 用 42）
#define RING_R_CUR_A            RING_ROW(37)            //  75  出环特征 A（E07 用 37）
#define RING_R_CUR_B            RING_ROW(35)            //  71  出环特征 B（E07 用 35）
#define RING_R_BOT              RING_ROW(55)            // 111  补线的底行锚点（E07 用 55）
#define RING_R_CTRL             RING_ROW(43)            //  87  环里的控制行（E07 用 43）

// 出环时"虚拟拐点"的列坐标（E07 state6 用的固定列 35 / 56，按 2.35 倍换算）
#define RING_C6_COL_L           (82)                    // E07 左环 buxian_r(60-len(35), 35)  -> 35*2.35
#define RING_C6_COL_R           (132)                   // E07 右环 buxian_l_R(60-len(35), 56) -> 56*2.35

//==================================================== 起环门槛 ================================================
// 【2026-10 实车实测，两轮读数】推车到各位置读屏幕（第二轮是修好 image_lost_r 之后重测的）：
//     场景        LEN   WID   LST(左81 左85 右81 右61)
//     直道         42   103   0000
//     左环入口     42   171   1100     <- 左边线真的跑出画面了
//     右环入口     43   151   0000     <- 右边线【没有】跑出画面，E07 的判据在这里失效
//   ① 路宽 WID 是唯一能把环岛和直道分开的实测特征：103 / 151 / 171。
//      门槛取 135 落在中间，两头都有余量。E07 的 wide_LR>45（图宽 80）换算过来是 106，
//      实测直道 103 就贴在旁边，太近 —— 所以不照抄 E07，按实测取 135。
//   ② 视野长度 LEN 已经【完全没有区分度】：直道 42 / 左环 42 / 右环 43。
//      它现在只是个"别在视野太短的时候起环"的保险（急弯约 34 会被它挡掉）。
//   ③ 起环的主力是 image.c 的 image_ring_side，不是这里的数字（原因见文件头那一段）。
#define RING_LONG_ROAD_MIN      (36)                    // 视野长度保险：中心列连续多少【采样行】还是白的
                                                        //   实测直道 42 / 左环 42 / 右环 43 都通过；急弯约 34 会被挡掉
#define RING_WIDE_MIN           (135)                    // 第 83 行的路面宽度下限（实测直道 103 / 左环 171 / 右环 151）


//==================================================== 拐点搜索（照 E07 Get_piont / Get_piont_R）===============
#define RING_CORNER_DX          (9)                     // 列方向邻域（E07 是 4 像素）
#define RING_CORNER_DY          (8)                     // 行方向邻域（E07 混用 3 和 4 行，这里统一成 8）
#define RING_CORNER_COL_LO      (RING_CORNER_DX)        // 左环搜索列范围（E07: 0..40）->  9..94
#define RING_CORNER_COL_HI      (IMAGE_W / 2)
#define RING_CORNER_R_COL_LO    (IMAGE_W / 2)           // 右环搜索列范围（E07: 38..75）-> 94..178
#define RING_CORNER_R_COL_HI    (IMAGE_W - 1 - RING_CORNER_DX)

//==================================================== 出环 ====================================================
#define RING_YAW_EXIT_L         (50.0f)                 // 【陀螺仪】左环 6->7：转过这么多度（E07: 50）
#define RING_YAW_EXIT_R         (40.0f)                 // 【陀螺仪】右环 6->7：转过这么多度（E07: 40）
#define RING_EXIT_TIMEOUT_FRAMES (75)                   // 7->0 的计时兜底：约 1.5 秒
                                                        //   E07: youchuhuandejishu > 300（按它的控制频率数的）
#define RING_WATCHDOG_FRAMES    (600)                   // 整个绕环过程的兜底计时（约 12 秒）
                                                        //   起环判据换成 image_ring_side 之后，万一是假特征起的环，
                                                        //   状态机会一直卡在里面（ring_on 挂着不放，后面的真环岛就进不来），
                                                        //   所以加一条总计时：超过这么多帧无条件复位 + 冷却。
                                                        //   E07 右环自己的出环兜底是 300 帧，600 是它的两倍，正常绕环用不到。
#define RING_COOLDOWN_FRAMES    (250)                   // 出环后的冷却帧数（约 5 秒），防止同一个环被重复识别
                                                        //   E07: timer_L = 1000

//==================================================== 环里的舵机参数（照 E07 duoji_pid）=========================
//   E07 正常 P=0.32，进环后 P=0.38（+19%），D 不变，I 清零。本工程按同样比例放大 KP/KP2，KD 不变。
#define RING_STEER_KP           (1.9f)                  // TRACK_STEER_KP  1.6   x 1.19
#define RING_STEER_KP2          (0.042f)                // TRACK_STEER_KP2 0.035 x 1.19
#define RING_STEER_KD           (0.45f)                 // 和正常一样（E07 也不变）

//==================================================== 环里的速度上限 ==============================================
#define RING_SPEED_MAX          (138.0f)                // 环岛目标速度上限（脉冲/20ms）
                                                        //   E07: yvan_speed = 140，比它正常速度低不少才绕得住；
                                                        //   本工程约等于直道 600 的 23%，比弯心 153 略低一点

//==================================================== 结果 ====================================================
extern uint8   ring_on;                                 // 1 = 正在绕环（对应 E07 的 cir_flag_l / cir_flag_R）
extern uint8   ring_state;                              // 1..7 = 当前阶段（对应 cir_flag1..7）；0 = 不在环里
extern uint8   ring_side;                               // 1 = 左环  2 = 右环
extern uint8   ring_long_road;                          // 视野长度（诊断用）
extern int16   ring_wide;                               // 第 83 行路宽（诊断用）
extern uint8   ring_corner_ok;                          // 本帧找到拐点了吗（诊断用）

//==================================================== 对外接口 ====================================================
void  ring_update    (void);                            // image_process() 最后会自己调，不用用户管
uint8 ring_is_active (void);
uint8 ring_get_state (void);

#endif
