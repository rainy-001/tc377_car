/*********************************************************************************************************************
* 文件名称          servo.c
* 功能简介          舵机 PWM 输出（含中值标定 + 硬限位扫描）
*********************************************************************************************************************/

#include "servo.h"

//==================================================== 内部变量 ====================================================
static uint16 servo_duty_now = SERVO_MID_DUTY;          // 当前输出的占空比

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      舵机初始化
// 备注信息      一律停在中值（顺便可以检查前轮正不正）。
//               标定模式也从这里出发 —— servo_sweep_update() 会从中值往两边扫。
//-------------------------------------------------------------------------------------------------------------------
void servo_init (void)
{
    pwm_init(SERVO_PWM_PIN, SERVO_PWM_FREQ, SERVO_MID_DUTY);
    servo_duty_now = SERVO_MID_DUTY;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      【标定用】硬限位扫描，在主循环里反复调用
// 备注信息      SERVO_SWEEP_ENABLE = 1 时：
//                 ① 从中值出发，一档一档往【占空比小的方向】走，走到 SERVO_SWEEP_MIN 停一档；
//                 ② 回到中值，再一档一档往【占空比大的方向】走，走到 SERVO_SWEEP_MAX 停一档；
//                 ③ 循环。
//
//               怎么读：盯住屏幕上的 DTY，记下【轮子不再继续转、舵机开始嗡嗡叫】那一刻的数值，
//                 那个值就是这一侧的真实机械限位，两个方向各记一个。
//               SERVO_SWEEP_ENABLE = 0 时这个函数什么都不做。
//-------------------------------------------------------------------------------------------------------------------
void servo_sweep_update (void)
{
#if (SERVO_SWEEP_ENABLE)
    static uint32 last_ms = 0;
    static uint8  side    = 0;                          // 0 = 正在往占空比小的方向扫，1 = 正在往大的方向扫
    static int16  mag     = 0;                          // 本方向已经离开中值多少（占空比单位）
    int32         duty;
    uint32        now_ms;

    now_ms = system_getval_ms();

    if(0 == last_ms)
    {
        last_ms = now_ms;                               // 第一次调用只记时间
        return;
    }

    if((now_ms - last_ms) < SERVO_SWEEP_HOLD_MS)
    {
        return;                                         // 这一档还没停够
    }
    last_ms = now_ms;

    if(0 == side)
    {
        duty = (int32)SERVO_MID_DUTY - (int32)mag;

        if(duty <= (int32)SERVO_SWEEP_MIN)
        {
            duty = (int32)SERVO_SWEEP_MIN;              // 这一侧到底，停一档再换方向
            side = 1;
            mag  = 0;
        }
        else
        {
            mag += SERVO_SWEEP_STEP;
        }
    }
    else
    {
        duty = (int32)SERVO_MID_DUTY + (int32)mag;

        if(duty >= (int32)SERVO_SWEEP_MAX)
        {
            duty = (int32)SERVO_SWEEP_MAX;              // 这一侧到底，停一档再换方向
            side = 0;
            mag  = 0;
        }
        else
        {
            mag += SERVO_SWEEP_STEP;
        }
    }

    servo_duty_now = (uint16)duty;
    pwm_set_duty(SERVO_PWM_PIN, (uint16)duty);
#endif
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      直接设置舵机占空比
// 参数说明      duty            占空比（50Hz 标度，1 个单位 = 2us），内部夹在 SAFE 范围里
//-------------------------------------------------------------------------------------------------------------------
void servo_set_duty (uint16 duty)
{
#if (SERVO_SWEEP_ENABLE)
    return;                                             // 标定模式：不接受上层指令，免得跟扫描打架
#endif

    if(duty > SERVO_SAFE_MAX) { duty = SERVO_SAFE_MAX; }
    if(duty < SERVO_SAFE_MIN) { duty = SERVO_SAFE_MIN; }

    servo_duty_now = duty;
    pwm_set_duty(SERVO_PWM_PIN, duty);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      相对中值给偏移量
// 参数说明      offset          偏移量，正数 = 占空比变大
// 备注信息      内部夹在 SERVO_MIN_DUTY / SERVO_MAX_DUTY 之间（= 实测机械限位 ± SERVO_LOCK_MARGIN），
//               所以上层就算算出再大的打角也顶不到机械限位、更不会堵转。
//               注意两边行程可以不一样，这里本来就是分开夹的。
//-------------------------------------------------------------------------------------------------------------------
void servo_set_offset (int16 offset)
{
    int32 duty = (int32)SERVO_MID_DUTY + (int32)offset;

    if(duty > (int32)SERVO_MAX_DUTY) { duty = (int32)SERVO_MAX_DUTY; }
    if(duty < (int32)SERVO_MIN_DUTY) { duty = (int32)SERVO_MIN_DUTY; }

    servo_set_duty((uint16)duty);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取当前输出的占空比
//-------------------------------------------------------------------------------------------------------------------
uint16 servo_get_duty (void)
{
    return servo_duty_now;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      读取当前输出相对中值的偏移
//-------------------------------------------------------------------------------------------------------------------
int16 servo_offset (void)
{
    return (int16)((int32)servo_duty_now - (int32)SERVO_MID_DUTY);
}