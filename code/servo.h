/*********************************************************************************************************************
* 文件名称          servo.h
* 功能简介          舵机 PWM 输出（P33_9）
*********************************************************************************************************************/

#ifndef _servo_h_
#define _servo_h_

#include "zf_common_headfile.h"

//==================================================== 接线 ====================================================
// 舵机 PWM = P33_9
//
// 【这个坑一定要注意】P33_9 在逐飞库里对应两个通道：ATOM0_CH1_P33_9 和 ATOM1_CH1_P33_9。
//   而电机1 的 PWM 用的是 ATOM0_CH1_P21_3 —— 它和 ATOM0_CH1_P33_9 是【同一个 ATOM 通道】，
//   一个通道只能输出一路波形。要是这里写成 ATOM0_CH1_P33_9，
//   舵机会跟着电机1 一起动（电机转多快舵机就打多大），所以必须用 ATOM1_CH1_P33_9。
#define SERVO_PWM_PIN       (ATOM1_CH1_P33_9)

//==================================================== 频率 ====================================================
// 模拟舵机（S3010 之类）只能 50Hz，绝对不能调高，高了会烧；
// 数字舵机可以 100~333Hz，响应更快。不确定就保持 50Hz，一定不会出事。
#define SERVO_PWM_FREQ      (50)

//==================================================== 占空比标定 ====================================================
// 50Hz 时一个周期是 20ms，PWM_DUTY_MAX = 10000，所以 1 个单位 = 2us。本车实测过的参考点：
//     590 = 1.180ms   750 = 1.500ms   770 = 1.540ms   920 = 1.840ms
//   SERVO_MID_DUTY = 770 是"前轮朝正前方"的位置（实测标定）。
#define SERVO_MID_DUTY      (770)                       // 中值占空比（已实测标定：770 时前轮正）

//-------------------------------------------- 左右行程必须分开标定 --------------------------------------------
// 行程端点 = 舵机和连杆真正顶到机械限位的位置。顶过去舵机就一直堵转"嗡嗡"叫
// （会烫、会拉低电源，严重时板子复位），所以端点必须【留在真实限位里面】。
// 中值 770 是"前轮朝正前方"，它由舵机盘齿位和连杆长度决定，几乎不会正好落在机械行程中点，
// 所以两个方向必须分开设 —— 对称设的后果就是一边没用完、另一边顶死。
//
// 【本车实测记录】
//     640 / 900  -> 端点不叫，但右转打角不够          （安全，可惜行程没用到头）
//     520 / 980  -> 转向够了，两个方向打满都嗡嗡叫     （冲过限位了）
//     硬限位扫描 -> 往小的一侧 590 起叫，往大的一侧 920 起叫
//   590 落在 (530, 640] 里、920 落在 [900, 970) 里，和上面两次测试的括号完全吻合，交叉验证通过。
//   也就是说原来 640 / 900 白丢了 50 / 20 个单位的真实可用转角，现在收回来了。
#define SERVO_LOCK_LOW      (660)                       // 实测：占空比【小】侧 590 起叫（右转走这边）
#define SERVO_LOCK_HIGH     (880)                       // 实测：占空比【大】侧 920 起叫（左转走这边）

// 顶到机械限位舵机就堵转发热，所以实际行程再往里留一点余量
#define SERVO_LOCK_MARGIN   (10)

#define SERVO_MIN_DUTY      (SERVO_LOCK_LOW  + SERVO_LOCK_MARGIN)   // 600 = 1.200ms
#define SERVO_MAX_DUTY      (SERVO_LOCK_HIGH - SERVO_LOCK_MARGIN)   // 910 = 1.820ms

// 两边各自的行程（track.c 的转角换算按各自行程归一化，所以左右不对称也没问题）
#define SERVO_TRAVEL_LOW    (SERVO_MID_DUTY - SERVO_MIN_DUTY)       // 770 - 600 = 170
#define SERVO_TRAVEL_HIGH   (SERVO_MAX_DUTY - SERVO_MID_DUTY)       // 910 - 770 = 140
#define SERVO_TRAVEL        (SERVO_TRAVEL_LOW > SERVO_TRAVEL_HIGH ? SERVO_TRAVEL_LOW : SERVO_TRAVEL_HIGH)

// 硬保护：最终输出一定会被夹在这里。取舵机标称的 1.00ms ~ 2.00ms（500 ~ 1000），
// 比实测限位宽，所以 SERVO_LOCK_* 填多少都不会被这一层挡住。
#define SERVO_SAFE_MIN      (500)
#define SERVO_SAFE_MAX      (1000)

//==================================================== 硬限位扫描（标定用）====================================================
// 已经标定完成，SERVO_SWEEP_ENABLE = 0。将来换了舵机或动了连杆，再按下面步骤重量一次。
//
// SERVO_SWEEP_ENABLE = 1 时【车不会动：servo_set_duty() 直接返回】，只用来量限位。
// servo_sweep_update() 的扫描过程：
//     ① 从中值 770 出发，一档一档往【占空比小的方向】走，走到 SERVO_SWEEP_MIN 停一档；
//     ② 回到中值，再一档一档往【占空比大的方向】走，走到 SERVO_SWEEP_MAX 停一档；
//     ③ 循环，一圈约 55 秒。
// 盯住屏幕 DTY，记下【轮子不再继续转、舵机开始嗡嗡叫】那一刻的数值，就是这一侧的真实限位。
// SERVO_SWEEP_MIN / MAX 取"已知会叫"的两个值即可 —— 真实限位必定在它们里面。
#define SERVO_SWEEP_ENABLE      (0)                     // 1 = 硬限位扫描（车不会动）；已标定完成
#define SERVO_SWEEP_MIN         (530)                   // 扫描下限
#define SERVO_SWEEP_MAX         (970)                   // 扫描上限
#define SERVO_SWEEP_STEP        (10)                    // 每档差多少（10 = 20us）
#define SERVO_SWEEP_HOLD_MS     (1200)                  // 每档停多久（毫秒）

//==================================================== 对外接口 ====================================================
void   servo_init       (void);                         // 初始化并回中
void   servo_sweep_update(void);                       // 标定模式：硬限位扫描，主循环里反复调用
void   servo_set_duty   (uint16 duty);                  // 直接给占空比（内部限幅到 SAFE 范围）
void   servo_set_offset (int16 offset);                 // 给相对中值的偏移（内部限幅到 MIN/MAX 行程）
uint16 servo_get_duty   (void);                         // 当前输出占空比
int16  servo_offset     (void);                         // 当前输出相对中值的偏移

#endif
