/*********************************************************************************************************************
* 文件名称          vofa.h
* 功能简介          VOFA+ 上位机串口通信：JustFloat 波形上传 + ASCII 在线调参
*
* *************************** 接线 ***************************
*   默认用 UART0：TX = P14_0，RX = P14_1
*   这两个脚就是逐飞 TC377 核心板"烧录/调试"USB 口上那路串口（和库里 DEBUG_UART 的默认引脚一致）。
*   如果板子的串口不在 P14_0/P14_1，只改下面 VOFA_UART / VOFA_TX_PIN / VOFA_RX_PIN 三个宏。
*   【注意】不要再往同一个串口打 printf：文字会把 JustFloat 的二进制帧冲散。
*
* *************************** 波形格式 ***************************
*   VOFA+ 里数据格式选 JustFloat：N 个 float（小端）+ 4 字节帧尾 00 00 80 7F
*   本工程 N = 12，一帧 52 字节；默认 460800 波特率、50 Hz 发送，一帧约 1.1 ms 发完。
*   如果 460800 打不开（少数 USB 转串口芯片不支持），把 VOFA_BAUD 改成 115200 即可
*   （115200 时一帧约 4.5 ms，仍然够用，只是主循环每 20 ms 多花几毫秒）。
*
*   通道顺序（VOFA+ 里按这个顺序命名图例）：
*       0  T1   电机1 目标速度（脉冲/20ms）
*       1  A1   电机1 实际速度
*       2  T2   电机2 目标速度
*       3  A2   电机2 实际速度
*       4  D1   电机1 占空比（%，0~100）
*       5  D2   电机2 占空比（%）
*       6  ERR  图像偏差（像素，正 = 赛道中心偏右）
*       7  SDR  舵机打角（占空比偏移）
*       8  RAT  弯道减速比例（0~100）
*       9  SPD  直道基础速度设定
*      10  YAW  航向角（度，右转为负）
*      11  VLD  有效边线行数
*
* *************************** 在线调参 ***************************
*   VOFA+ 的"命令"面板发送 ASCII，一行一条（发送时勾选"换行"）：
*
*       p 2.0 0.5 0            两个电机 PID 一起改（Kp Ki Kd）
*       p1 2.2 0.6 0           只改电机1；p2 同理
*       spd 600                直道基础速度（脉冲/20ms）
*       dir 1.6 0.035 0.45     转向 Kp / Kp2 / Kd
*       curve 0.255 40         弯道最低速度比例 / 减速参考偏差（GAIN 自动 = 1 - 比例）
*       diff 1.35              电子差速增益
*       thr 20                 二值化阈值偏移（-60 ~ +60）
*       start / stop           起跑 / 停车
*
*   命令故意不回应答：回文字会把波形打断。改没改看波形和屏幕上的数值。
*   所有参数都在下位机里做了限幅，填错大不了不生效，不会把车搞飞。
*********************************************************************************************************************/

#ifndef _vofa_h_
#define _vofa_h_

#include "zf_common_headfile.h"

//==================================================== 硬件配置 ====================================================
#define VOFA_UART           (UART_0)                    // 串口通道
#define VOFA_TX_PIN         (UART0_TX_P14_0)            // 发送脚
#define VOFA_RX_PIN         (UART0_RX_P14_1)            // 接收脚
#define VOFA_BAUD           (460800)                    // 波特率（和 VOFA+ 里保持一致）
#define VOFA_PERIOD_MS      (20)                        // 发送周期（20ms = 50Hz）

//==================================================== 通道数 ====================================================
#define VOFA_CH_NUM         (12)                        // 和下面的 vofa_fill() 一一对应

//==================================================== 对外接口 ====================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介      串口 + 接收中断初始化
// 备注信息      在 cpu0_main.c 里、pit_ms_init() 之前调用一次
//-------------------------------------------------------------------------------------------------------------------
void vofa_init          (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      主循环调用：解析收到的命令 + 按周期发一帧波形
// 备注信息      内部自己按 VOFA_PERIOD_MS 分频，主循环里无条件反复调用即可
//-------------------------------------------------------------------------------------------------------------------
void vofa_update        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介      【串口接收中断里调用】把收到的字节塞进环形缓冲
// 备注信息      在 user/isr.c 的 uart0_rx_isr 里调用
//-------------------------------------------------------------------------------------------------------------------
void vofa_uart_callback (void);

#endif
