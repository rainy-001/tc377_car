/*********************************************************************************************************************
* 文件名称          cpu0_main.c
* 功能简介          主程序：摄像头循迹（图像处理 + 舵机转向 + 两轮差速）
*
* *************************** 接线 ***************************
*   电机1：P21_3 = PWM    P21_2 = DIR(低电平正转)    编码器1：P10_3 + P10_1
*   电机2：P21_5 = PWM    P21_4 = DIR(低电平正转)    编码器2：P20_3 + P20_0
*   舵机 ：P33_9 = PWM（走 ATOM1_CH1，不是 ATOM0_CH1 —— 见 code/servo.h 里的说明）
*   摄像头（总钻风 MT9V03X）：
*       PCLK P02_1    VSY P02_0    D0~D7 P00_0~P00_7    配置串口 P02_2 / P02_3
*   IPS200 Pro：SCLK P15_3  MOSI P15_5  CS P15_2  RES P15_1  DC P15_0  BL P15_4
*
* *************************** 本程序做什么 ***************************
*   1. 初始化屏幕、编码器、电机、舵机、摄像头
*   2. CCU60_CH0 定时中断每 20ms 做一次：采编码器 + 采陀螺仪 + 跑两路速度环（在 user/isr.c 里）
*      —— 速度环放在中断里，主循环里刷屏/处理图像再慢也不会打乱 20ms 节拍
*   3. 主循环：一有新的一帧图像（约 50 帧/秒）就 图像处理 -> 循迹控制
*   4. 每 150ms 刷一次屏幕（图像 + 状态数字）
*   5. 摄像头掉线超过 200ms 立刻停车（防止跑飞）
*
* *************************** 速度单位 ***************************
*   速度 = 脉冲 / 20ms（一个控制周期）
*   屏幕上 T1/T2 = 目标速度，A1/A2 = 实际速度
*
* *************************** 参数在哪 ***************************
*   摄像头/图像   code/image.h 顶部（阈值、扫描行、赛道类型、偏差算法）
*   舵机          code/servo.h 顶部（中值标定、行程、频率）
*   循迹控制      code/track.h 顶部（转向 KP/KD、弯道减速、电子差速、电机左右）
*   电机速度环    code/motor.c 顶部（目标速度、PID 参数）
*********************************************************************************************************************/

#include "zf_common_headfile.h"
#include "cpu0_main.h"
// 【必须用 ../code/ 相对路径】本工程的 include 路径里混进了示例工程
// （Seekfree_TC377_Opensource_Library）的一百多条目录，而且排在本工程 code\ 前面。
// code\ 下的 .c 靠"先找当前文件所在目录"能拿到自己的头文件，user\ 下没有这个便利，
// 裸写 "motor.h" 会命中示例工程那份 API 完全不同的头文件（这就是之前
// implicit declaration / SERVO_MID_DUTY undeclared 的原因）。相对路径绕开顺序问题。
#include "../code/motor.h"
#include "../code/encoder.h"
#include "../code/display.h"
#include "../code/camera.h"
#include "../code/image.h"
#include "../code/servo.h"
#include "../code/track.h"
#include "../code/imu.h"

#pragma section all "cpu0_dsram"
// 将本语句与#pragma section all restore语句之间的全局变量都放在CPU0的RAM中

//==================================================== 时间参数 ====================================================
#define ENCODER_UPDATE_MS       (20)            // 编码器采样 + 速度环周期（CCU60_CH0 定时中断）
#define DISPLAY_TRACK_MS        (150)           // 循迹页面刷新周期

//==================================================== 摄像头看门狗 ====================================================
// 超过这么久没有新的一帧，就认为摄像头掉线/初始化失败，立刻把车停住
#define CAMERA_LOST_MS          (200)

//==================================================== 全局变量 ====================================================
uint32 last_display_ms = 0;

//==================================================== 主函数 ====================================================
int core0_main(void)
{
    // 时钟初始化（关看门狗、初始化系统延时），必须最先调用
    clock_init();

    // 等待其它核心初始化完毕
    cpu_wait_event_ready();

    // ------------------------------- 屏幕 -------------------------------
    display_init();
    display_show_period(ENCODER_UPDATE_MS);

    // ------------------------------- 编码器 + 电机 -------------------------------
    encoder_init();                             // 编码器采样由 CCU60_CH0 中断驱动
    motor_init();
    motor_stop_all();                           // 上电先停住

    // ------------------------------- 舵机 -------------------------------
    servo_init();                               // 初始化并回中，方便检查前轮正不正

    // ------------------------------- 陀螺仪（初始化后由 20ms 中断周期采样）------------------------------
    // 放在舵机之后、摄像头之前：这时车还是静止的，静止校零才准。
    // （不要放到 servo_init() 前面 —— 舵机刚动过会晃，校零就不准了。）
    // 内部会阻塞约 0.4 秒做校零采样。
    imu_init();

    // ------------------------------- 摄像头 -------------------------------
    // mt9v03x_init() 内部有 200ms 延时和串口协商，会阻塞几百毫秒，所以放在最后面
    camera_setup();
    image_init();

    // ------------------------------- 循迹控制 -------------------------------
    track_init();

    // ------------------------------- 最后再开定时中断 -------------------------------
    // 20ms 一次，中断里同时做 编码器采样 + 两路速度环
    pit_ms_init(CCU60_CH0, ENCODER_UPDATE_MS);

    last_display_ms = system_getval_ms();

    while (TRUE)
    {
        uint32 now_ms = system_getval_ms();

        // 舵机中值标定：SERVO_SWEEP_ENABLE = 1 时这里会自动扫，= 0 时是空函数
        servo_sweep_update();

        // ------------------------------- 图像 + 循迹（约 50 帧/秒）------------------------------
        if (camera_update())                    // 有新的一帧（已经拷到 camera_image）
        {
            image_process();                    // 大津法二值化 -> 左右边线 -> 中线 -> 偏差
            track_update();                     // 舵机打角 + 弯道减速 + 两轮电子差速
        }

        // ------------------------------- 摄像头看门狗 -------------------------------
        if (camera_get_idle_ms() > CAMERA_LOST_MS)
        {
            motor_stop_all();
            servo_set_duty(SERVO_MID_DUTY);
        }

        // ------------------------------- 屏幕 -------------------------------
        if ((now_ms - last_display_ms) >= DISPLAY_TRACK_MS)
        {
            last_display_ms = now_ms;
            display_update_track();
        }

        // 这一圈用完了，放行摄像头中断去拷下一帧
        camera_release();
    }
}

#pragma section all restore
